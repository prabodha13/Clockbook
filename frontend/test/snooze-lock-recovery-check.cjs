const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../src/App.jsx'), 'utf8');
const functionBody = source.match(/function noTrackAlertWindows\(alert, endMs = Date\.now\(\)\) \{[\s\S]*?\n\}/)?.[0];
assert.ok(functionBody, 'recovery slice helper exists');
const context = vm.createContext({});
vm.runInContext(`${functionBody}\nthis.windows = noTrackAlertWindows`, context);
const segments = context.windows;
const original = { since: 0 };
const frozen = { since: 120000, until: 120000, windows: segments(original, 120000) };
const resumed = { since: 600000, windows: frozen.windows };
const result = segments(resumed, 780000);
assert.deepEqual(JSON.parse(JSON.stringify(result)), [{start:0,end:120000},{start:600000,end:780000}]);
const handler = source.match(/onSnooze=\{\(snoozeMs\) => \{([\s\S]*?)\n          \}\}/)?.[1];
assert.ok(handler, 'snooze handler exists');
assert.ok(handler.includes('setNoTrackSnoozeUntil('), 'snooze deadline set');
assert.ok(!handler.includes('setIdleNoTrackAlert(null)'), 'snooze must not erase recovery alert');
assert.ok(!handler.includes('idleNoTrackAlertRef.current = null'), 'snooze must preserve recovery ref');
assert.ok(source.includes('idleNoTrackAlert && !sleepAlert && noTrackSnoozeUntil <= Date.now()'), 'snooze hides modal until expiry');
assert.ok(source.includes('const hadRecoveryReminder = !!idleNoTrackAlertRef.current;\n          freezeNoTrackWindow(lockedSince);'), 'OS lock freezes pending recovery');
assert.ok(source.includes('resumeNoTrackWindow(returnedAt);'), 'unlock resumes after the away period');
console.log('PASS: snooze preserves pending recovery, lock/unlock excludes Away time, reminder suppression is time-bound');
